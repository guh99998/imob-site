import io

import pytest
from django.core.exceptions import ValidationError
from django.core.files.uploadedfile import SimpleUploadedFile
from django.db.models import ProtectedError
from PIL import Image

from apps.properties.models import (
    MAX_PHOTO_SIZE,
    Category,
    City,
    Neighborhood,
    Property,
    PropertyPhoto,
)

from .factories import PropertyFactory

pytestmark = pytest.mark.django_db


def make_image(size=(3000, 2000)):
    buf = io.BytesIO()
    Image.new("RGB", size, "red").save(buf, format="JPEG")
    return SimpleUploadedFile("big.jpg", buf.getvalue(), content_type="image/jpeg")


@pytest.mark.parametrize(
    "purpose,sale,rent,field",
    [
        (Property.Purpose.SALE, None, 1000, "sale_price"),
        (Property.Purpose.RENT, 1000, None, "rent_price"),
        (Property.Purpose.BOTH, 1000, None, "rent_price"),
        (Property.Purpose.BOTH, None, 1000, "sale_price"),
    ],
)
def test_price_required_by_purpose(purpose, sale, rent, field):
    prop = PropertyFactory.build(purpose=purpose, sale_price=sale, rent_price=rent)
    with pytest.raises(ValidationError) as exc:
        prop.clean()
    assert field in exc.value.message_dict


def test_valid_both_purposes():
    PropertyFactory.build(purpose="BOTH", sale_price=1, rent_price=1).clean()


def test_published_excludes_drafts():
    pub = PropertyFactory()
    PropertyFactory(status=Property.Status.DRAFT)
    sold = PropertyFactory(status=Property.Status.SOLD)
    assert set(Property.objects.published()) == {pub, sold}
    assert list(Property.objects.available()) == [pub]


def test_published_at_set_on_publish():
    prop = PropertyFactory(status=Property.Status.DRAFT)
    assert prop.published_at is None
    prop.status = Property.Status.PUBLISHED
    prop.save()
    assert prop.published_at is not None


def test_slug_autogenerated():
    base = PropertyFactory()
    prop = Property(
        code="X1",
        title="Casa Bonita",
        category=base.category,
        neighborhood=base.neighborhood,
        sale_price=1,
    )
    prop.save()
    assert prop.slug == "x1-casa-bonita"


def test_code_autogenerated_sequentially():
    base = PropertyFactory()
    kwargs = {"category": base.category, "neighborhood": base.neighborhood, "sale_price": 1}
    first = Property.objects.create(title="A", **kwargs)
    second = Property.objects.create(title="B", **kwargs)
    assert first.code == "DLM-0001" and second.code == "DLM-0002"
    assert second.slug == "dlm-0002-b"


def test_slug_collision_gets_suffix():
    base = PropertyFactory()
    kwargs = {"category": base.category, "neighborhood": base.neighborhood, "sale_price": 1}
    first = Property.objects.create(code="A", title="b c", **kwargs)
    second = Property.objects.create(code="A-b", title="c", **kwargs)
    assert first.slug == "a-b-c" and second.slug == "a-b-c-2"


def test_city_and_neighborhood_slug_autogenerated():
    city = City.objects.create(name="São José", state="SP")
    assert city.slug == "sao-jose"
    assert City.objects.create(name="Sao Jose", state="MG").slug == "sao-jose-2"
    nb = Neighborhood.objects.create(city=city, name="Centro Velho")
    assert nb.slug == "centro-velho"


def test_category_slug_and_protect():
    cat = Category.objects.create(name="Casa de Praia")
    assert cat.slug == "casa-de-praia"
    PropertyFactory(category=cat)
    with pytest.raises(ProtectedError):
        cat.delete()


def test_photo_resized_and_single_cover():
    prop = PropertyFactory()
    first = PropertyPhoto.objects.create(property=prop, image=make_image(), is_cover=True)
    assert first.image.width <= MAX_PHOTO_SIZE[0]
    assert first.image.height <= MAX_PHOTO_SIZE[1]
    second = PropertyPhoto.objects.create(
        property=prop, image=make_image((100, 100)), is_cover=True
    )
    first.refresh_from_db()
    assert not first.is_cover and second.is_cover
    assert Property.objects.get(pk=prop.pk).cover == second


def test_address_hidden_by_default():
    prop = PropertyFactory(street="Rua A", number="10")
    assert "Rua A" not in prop.full_address
    prop.show_address = True
    assert "Rua A, 10" in prop.full_address


